import pg from 'pg';
import { config } from './config.js';

// BIGINT / NUMERIC reviennent en nombres JS (les montants restent bien en dessous de 2^53).
pg.types.setTypeParser(20, Number);
pg.types.setTypeParser(1700, Number);

// Horodatage UTC au format 'YYYY-MM-DD HH24:MI:SS' (même format texte qu'avant la migration).
export const NOW = "to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')";
export const AGO = (interval) => `to_char((now() at time zone 'utc') - interval '${interval}', 'YYYY-MM-DD HH24:MI:SS')`;

const toPg = (sql) => {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
};

// Petite API async : get / all / run, avec des placeholders "?".
function wrap(runner) {
  const q = (sql, params) => runner.query(toPg(sql), params);
  return {
    all: async (sql, ...p) => (await q(sql, p)).rows,
    get: async (sql, ...p) => (await q(sql, p)).rows[0],
    run: async (sql, ...p) => {
      const r = await q(sql, p);
      return { changes: r.rowCount, rows: r.rows };
    },
  };
}

const SCHEMA_SQL = `
  CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    pass_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user','admin')),
    balance BIGINT NOT NULL DEFAULT 0 CHECK (balance >= 0),
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );

  CREATE TABLE IF NOT EXISTS matches (
    id BIGINT PRIMARY KEY,
    date TEXT NOT NULL,
    kickoff_utc TEXT,
    league_id BIGINT,
    league_name TEXT,
    home_team TEXT NOT NULL,
    away_team TEXT NOT NULL,
    status TEXT NOT NULL,
    minute TEXT,
    home_score INTEGER,
    away_score INTEGER,
    result INTEGER,
    penalty_home INTEGER,
    penalty_away INTEGER,
    voided INTEGER NOT NULL DEFAULT 0,
    home_logo TEXT,
    away_logo TEXT,
    updated_at TEXT NOT NULL DEFAULT ${NOW}
  );
  CREATE INDEX IF NOT EXISTS idx_matches_date ON matches(date);

  CREATE TABLE IF NOT EXISTS bets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL REFERENCES matches(id),
    creator_id BIGINT NOT NULL REFERENCES users(id),
    creator_side TEXT NOT NULL CHECK (creator_side IN ('home','away')),
    taker_id BIGINT REFERENCES users(id),
    stake BIGINT NOT NULL CHECK (stake > 0),
    status TEXT NOT NULL DEFAULT 'open'
      CHECK (status IN ('open','matched','settled','refunded','cancelled')),
    winner_id BIGINT REFERENCES users(id),
    payout BIGINT NOT NULL DEFAULT 0,
    commission BIGINT NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT ${NOW},
    matched_at TEXT,
    settled_at TEXT
  );
  CREATE INDEX IF NOT EXISTS idx_bets_match ON bets(match_id, status);

  CREATE TABLE IF NOT EXISTS ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id),
    type TEXT NOT NULL,
    amount BIGINT NOT NULL,
    balance_after BIGINT,
    ref TEXT,
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );
  CREATE INDEX IF NOT EXISTS idx_ledger_user ON ledger(user_id, id);

  CREATE TABLE IF NOT EXISTS payments (
    id TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    kind TEXT NOT NULL CHECK (kind IN ('deposit','withdrawal')),
    amount BIGINT NOT NULL CHECK (amount > 0),
    network TEXT NOT NULL,
    phone TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','success','failed')),
    saspay_id TEXT,
    checkout_url TEXT,
    created_at TEXT NOT NULL DEFAULT ${NOW},
    updated_at TEXT NOT NULL DEFAULT ${NOW}
  );
  CREATE INDEX IF NOT EXISTS idx_payments_user ON payments(user_id, created_at);

  CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    title TEXT NOT NULL,
    body TEXT NOT NULL,
    event_key TEXT,
    read INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT ${NOW}
  );
  ALTER TABLE notifications ADD COLUMN IF NOT EXISTS event_key TEXT;
  CREATE INDEX IF NOT EXISTS idx_notif_user ON notifications(user_id, id);
  CREATE UNIQUE INDEX IF NOT EXISTS idx_notif_user_event ON notifications(user_id, event_key) WHERE event_key IS NOT NULL;

  -- Supabase expose le schéma public via une API REST publique : RLS sans politique
  -- bloque tout accès par la clé anon/publique. Le serveur (rôle postgres) n'est pas concerné.
  ALTER TABLE users ENABLE ROW LEVEL SECURITY;
  ALTER TABLE matches ENABLE ROW LEVEL SECURITY;
  ALTER TABLE bets ENABLE ROW LEVEL SECURITY;
  ALTER TABLE ledger ENABLE ROW LEVEL SECURITY;
  ALTER TABLE payments ENABLE ROW LEVEL SECURITY;
  ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;
`;

// `schema` sert aux tests (schéma temporaire isolé). En production : schéma public.
export async function openDb({ url = config.databaseUrl, schema } = {}) {
  if (!url) throw new Error('DATABASE_URL manquante dans backend/.env');
  if (schema && !/^[a-z_][a-z0-9_]*$/.test(schema)) throw new Error('Nom de schéma invalide');
  const pool = new pg.Pool({ connectionString: url, ssl: { rejectUnauthorized: false }, max: 5 });
  pool.on('error', (err) => console.error('[pg]', err.message));
  if (schema) pool.on('connect', (c) => c.query(`SET search_path TO ${schema}, public`));
  if (schema) await pool.query(`CREATE SCHEMA IF NOT EXISTS ${schema}`);
  await pool.query(SCHEMA_SQL);
  return {
    ...wrap(pool),
    pool,
    close: async () => {
      if (schema) await pool.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
      await pool.end();
    },
  };
}

// Exécute fn(t) dans une transaction : tout ou rien. Verrouiller les lignes sensibles avec FOR UPDATE.
export async function tx(db, fn) {
  const client = await db.pool.connect();
  try {
    await client.query('BEGIN');
    const out = await fn(wrap(client));
    await client.query('COMMIT');
    return out;
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    client.release();
  }
}

export class BizError extends Error {
  constructor(message, status = 400) {
    super(message);
    this.status = status;
  }
}

// Modifie le solde d'un utilisateur (ou enregistre un mouvement plateforme si userId === null).
// À appeler dans une transaction.
export async function adjustBalance(t, userId, delta, type, ref = null) {
  if (!Number.isSafeInteger(delta)) throw new Error('Montant invalide');
  if (userId === null) {
    await t.run('INSERT INTO ledger (user_id, type, amount, ref) VALUES (NULL, ?, ?, ?)', type, delta, ref);
    return null;
  }
  const res = await t.run(
    'UPDATE users SET balance = balance + ? WHERE id = ? AND balance + ? >= 0 RETURNING balance',
    delta, userId, delta,
  );
  if (res.changes === 0) throw new BizError('Solde insuffisant', 402);
  const { balance } = res.rows[0];
  await t.run('INSERT INTO ledger (user_id, type, amount, balance_after, ref) VALUES (?, ?, ?, ?, ?)', userId, type, delta, balance, ref);
  return balance;
}

export async function notify(t, userId, title, body) {
  if (userId) await t.run('INSERT INTO notifications (user_id, title, body) VALUES (?, ?, ?)', userId, title, body);
}
